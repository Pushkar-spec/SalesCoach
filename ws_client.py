"""
WebSocket Client Helper for Streamlit Frontend (Step 1.6)

Provides a robust, synchronous WebSocket client wrapper using `websockets.sync.client`
to manage the connection lifecycle, ping/pong handshake, sales session lifecycle,
and graceful socket closure.
"""

import json
import logging
import os
from typing import Any, Optional
from websockets.sync.client import ClientConnection, connect

logger = logging.getLogger(__name__)

# Default development WebSocket endpoint
DEFAULT_BACKEND_WS_URL = "ws://127.0.0.1:8000/ws"


def get_backend_ws_url() -> str:
    """Retrieve the configured backend WebSocket URL from environment or default."""
    return os.getenv("BACKEND_WS_URL", DEFAULT_BACKEND_WS_URL)


class WebSocketClient:
    """
    Manages a single synchronous WebSocket connection lifecycle and session messages.

    Designed for Streamlit's script-rerun execution model:
    - Synchronous connection avoids complex async loops or background threads.
    - Connection state can be safely inspected across script reruns.
    - Supports ping/pong, start_session, status query, and stop_session.
    - Handshake or request failure cleans up immediately, leaving no stale sockets.
    """

    def __init__(
        self,
        url: Optional[str] = None,
        open_timeout: float = 3.0,
        recv_timeout: float = 3.0,
    ):
        self.url = url or get_backend_ws_url()
        self.open_timeout = open_timeout
        self.recv_timeout = recv_timeout
        self.connection: Optional[ClientConnection] = None

    @property
    def is_connected(self) -> bool:
        """Check if the underlying socket exists and is in an OPEN state."""
        return (
            self.connection is not None
            and hasattr(self.connection, "state")
            and getattr(self.connection.state, "name", None) == "OPEN"
        )

    def _send_and_receive(self, payload: dict[str, Any]) -> dict[str, Any]:
        """
        Helper to send a JSON payload and receive/parse the JSON response.

        Raises:
            ConnectionError: If the socket is not connected.
            TimeoutError: If the backend does not respond within recv_timeout.
            ValueError: If the response is not valid JSON or not a JSON object.
        """
        if not self.is_connected or self.connection is None:
            raise ConnectionError("WebSocket is not connected")

        self.connection.send(json.dumps(payload))
        raw_response = self.connection.recv(timeout=self.recv_timeout)

        try:
            response = json.loads(raw_response)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Malformed JSON response from backend: {exc}")

        if not isinstance(response, dict):
            raise ValueError("Expected JSON object in response from backend")

        return response

    def connect(self) -> None:
        """
        Establish connection to the backend WebSocket endpoint.
        """
        if not self.is_connected:
            self.connection = connect(
                self.url,
                open_timeout=self.open_timeout,
                close_timeout=self.open_timeout,
                legacy=True,
            )

    def connect_and_ping(
        self, ping_message: str = "Hello from Streamlit"
    ) -> dict[str, Any]:
        """
        Establish connection to backend and perform initial ping/pong handshake.

        Returns:
            dict: The validated pong response from the backend.

        Raises:
            ConnectionError / TimeoutError / ValueError / WebSocketException on failure.
        """
        try:
            self.connect()

            ping_payload = {"type": "ping", "message": ping_message}
            response = self._send_and_receive(ping_payload)

            if response.get("type") != "pong":
                raise ValueError(
                    f"Expected 'pong' response, received: {response.get('type')}"
                )

            if response.get("message") != ping_message:
                raise ValueError(
                    f"Pong message mismatch. Expected '{ping_message}', got '{response.get('message')}'"
                )

            return response

        except Exception as exc:
            self.close()
            raise exc

    def start_session(self) -> str:
        """
        Request the backend to start a new sales session.

        Returns:
            str: The confirmed unique session_id generated by the backend.

        Raises:
            RuntimeError: If the backend returns an error message.
            ValueError: If the response is invalid or missing session_id.
        """
        response = self._send_and_receive({"type": "start_session"})

        if response.get("type") == "error":
            raise RuntimeError(response.get("message", "Failed to start session"))

        if response.get("type") != "session_started":
            raise ValueError(
                f"Expected 'session_started' response, received: {response.get('type')}"
            )

        session_id = response.get("session_id")
        if not session_id or not isinstance(session_id, str):
            raise ValueError("Backend response missing valid 'session_id'")

        return session_id

    def get_status(self) -> dict[str, Any]:
        """
        Query current session status from the backend.

        Returns:
            dict: Status dictionary containing 'session_id' and 'status'.
        """
        response = self._send_and_receive({"type": "status"})

        if response.get("type") == "error":
            raise RuntimeError(response.get("message", "Failed to query status"))

        if response.get("type") != "status":
            raise ValueError(
                f"Expected 'status' response, received: {response.get('type')}"
            )

        return response

    def stop_session(self, session_id: str) -> dict[str, Any]:
        """
        Request the backend to stop the active session.

        Args:
            session_id: The ID of the session to stop.

        Returns:
            dict: Response confirming session has stopped.

        Raises:
            RuntimeError: If backend rejects the stop request.
            ValueError: If arguments or responses are invalid.
        """
        if not session_id or not isinstance(session_id, str):
            raise ValueError("session_id must be a non-empty string")

        response = self._send_and_receive({
            "type": "stop_session",
            "session_id": session_id,
        })

        if response.get("type") == "error":
            raise RuntimeError(response.get("message", "Failed to stop session"))

        if response.get("type") != "session_stopped":
            raise ValueError(
                f"Expected 'session_stopped' response, received: {response.get('type')}"
            )

        return response

    def close(self) -> None:
        """Gracefully close the connection and reset socket reference."""
        if self.connection is not None:
            try:
                self.connection.close()
            except Exception as e:
                logger.debug("Error while closing WebSocket: %s", e)
            finally:
                self.connection = None
